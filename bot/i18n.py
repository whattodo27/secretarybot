def t(lang: str, key: str, **kwargs) -> str:
    """Look up a UI string for ``lang`` (falls back to English), format with kwargs."""
    table = STRINGS.get(lang) or STRINGS["en"]
    text = table.get(key, STRINGS["en"].get(key, key))
    if kwargs:
        text = text.format(**kwargs)
    return text


def tr_recurrence(lang: str, recurrence: str) -> str:
    key = {"daily": "recur_daily", "weekly": "recur_weekly", "monthly": "recur_monthly"}.get(
        recurrence, "recur_none"
    )
    return t(lang, key)


