def format_dt(dt: datetime, lang: str, now: datetime | None = None) -> str:
    """Human date+time in a localized form, e.g. 'today 10:00' / 'Sat, 15.03 10:00'."""
    days = _WEEKDAY.get(lang, _WEEKDAY["en"])
    hhmm = dt.strftime("%H:%M")
    if now is not None and dt.date() == now.date():
        return f"{_TODAY.get(lang, 'today')} {hhmm}"
    if now is not None and dt.date() == (now.date().fromordinal(now.date().toordinal() + 1)):
        return f"{_TOMORROW.get(lang, 'tomorrow')} {hhmm}"
    return f"{days[dt.weekday()]}, {dt.strftime('%d.%m')} {hhmm}"